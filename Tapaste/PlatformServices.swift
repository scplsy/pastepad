@MainActor
final class ClipboardMonitor: ObservableObject {
    @Published private(set) var status: String?

    private let store: ClipboardStore
    private let settings: AppSettings
    private let pasteboard = NSPasteboard.general
    private var timer: Timer?
    private var lastChangeCount: Int
    private var ownChangeCount: Int?
    private var explicitlyAllowedLegacyReads = false
    private var contentStatus: String?

    private static let ownType = NSPasteboard.PasteboardType("app.tapaste.own-copy")
    private static let sourceType = NSPasteboard.PasteboardType("org.nspasteboard.source")
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
        NSPasteboard.PasteboardType("de.petermaurer.TransientPasteboardType"),
        NSPasteboard.PasteboardType("com.typeit4me.clipping"),
        NSPasteboard.PasteboardType("Pasteboard generator type"),
        .fileURL,
        NSPasteboard.PasteboardType("NSFilenamesPboardType"),
        ownType
    ]

    init(store: ClipboardStore, settings: AppSettings) {
        self.store = store
        self.settings = settings
        // Starting the app never imports whatever was already on the clipboard.
        self.lastChangeCount = NSPasteboard.general.changeCount
    }

    deinit {
        timer?.invalidate()
    }

    fileprivate var currentChangeCount: Int { pasteboard.changeCount }

    var pasteboardAccessDescription: String {
        if #available(macOS 15.4, *) {
            switch pasteboard.accessBehavior {
            case .alwaysAllow:
                return L("Allowed", "已允许")
            case .alwaysDeny:
                return L("Denied in System Settings", "已在系统设置中拒绝")
            case .ask:
                return L("Set clipboard access to Always Allow", "请将剪贴板访问设为始终允许")
            case .default:
                return explicitlyAllowedLegacyReads
                    ? L("Enabled", "已启用")
                    : L("Not requested", "尚未申请")
            @unknown default:
                return L("Clipboard access unavailable", "剪贴板访问不可用")
            }
        }
        return L("Available on this macOS version", "此 macOS 版本可直接访问")
    }

    func start() {
        guard timer == nil else { return }
        lastChangeCount = pasteboard.changeCount
        refreshStatus()
        let pollingTimer = Timer(timeInterval: 0.6, repeats: true) { [weak self] _ in
            Task { @MainActor [weak self] in self?.poll() }
        }
        RunLoop.main.add(pollingTimer, forMode: .common)
        timer = pollingTimer
    }

    /// Called only by an explicit user action; polling never requests permission.
    func requestPasteboardAccess() {
        lastChangeCount = pasteboard.changeCount
        if #available(macOS 15.4, *), pasteboard.accessBehavior == .alwaysDeny {
            refreshStatus()
            return
        }
        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: Self.ignoredTypes),
              let type = [.string, .png, .tiff].first(where: types.contains) else {
            contentStatus = L(
                "Copy a non-sensitive text or image, then enable clipboard access.",
                "请先复制一段非敏感文本或图片，再启用剪贴板访问。"
            )
            status = contentStatus
            return
        }

        // NSPasteboard has no separate permission request or byte-length API.
        // Read one supported representation, discard it, and do not import it.
        let readSucceeded = pasteboard.data(forType: type) != nil
        explicitlyAllowedLegacyReads = readSucceeded
        contentStatus = readSucceeded ? nil : L(
            "Clipboard access was not granted. Check System Settings.",
            "未获得剪贴板访问权限，请检查系统设置。"
        )
        lastChangeCount = pasteboard.changeCount
        refreshStatus()
    }

    func openPasteboardSettings() {
        if let url = URL(string: "x-apple.systempreferences:com.apple.preference.security") {
            NSWorkspace.shared.open(url)
        }
    }

    @discardableResult
    func copy(_ item: ClipboardItem) -> Bool {
        let clipboardItem = NSPasteboardItem()
        switch item.kind {
        case .text:
            guard clipboardItem.setString(item.text, forType: .string) else {
                contentStatus = L("This text could not be copied.", "无法复制此文本。")
                refreshStatus()
                return false
            }
        case .image:
            guard let url = store.imageURL(for: item),
                  let data = try? Data(contentsOf: url, options: .mappedIfSafe),
                  clipboardItem.setData(data, forType: .png) else {
                contentStatus = L("The saved image is unavailable.", "保存的图片不可用。")
                refreshStatus()
                return false
            }
        }
        clipboardItem.setData(Data(), forType: Self.ownType)
        clipboardItem.setString(Bundle.main.bundleIdentifier ?? "app.tapaste", forType: Self.sourceType)
        pasteboard.clearContents()
        let copied = pasteboard.writeObjects([clipboardItem])
        ownChangeCount = pasteboard.changeCount
        lastChangeCount = pasteboard.changeCount
        if copied {
            // Persist reuse after this event; the open panel keeps its display order.
            DispatchQueue.main.async { [weak self] in self?.store.recordReuse(item.id) }
        }
        contentStatus = copied ? nil : L("The clipboard could not be updated.", "无法更新系统剪贴板。")
        refreshStatus()
        return copied
    }

    private var canReadAutomatically: Bool {
        if #available(macOS 15.4, *) {
            switch pasteboard.accessBehavior {
            case .alwaysAllow: return true
            case .default: return explicitlyAllowedLegacyReads
            case .ask, .alwaysDeny: return false
            @unknown default: return false
            }
        }
        return true
    }

    private func refreshStatus() {
        let nextStatus: String?
        if settings.paused {
            nextStatus = L("Clipboard recording is paused.", "剪贴板记录已暂停。")
        } else if !canReadAutomatically {
            nextStatus = L(
                "Enable clipboard access in Settings. Background reads will not request permission repeatedly.",
                "请在设置中启用剪贴板访问；后台记录不会反复申请权限。"
            )
        } else {
            nextStatus = contentStatus
        }
        if status != nextStatus { status = nextStatus }
    }

    private func poll() {
        refreshStatus()
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        // Advance even when paused or blocked so skipped content isn't imported later.
        lastChangeCount = changeCount
        guard !settings.paused, changeCount != ownChangeCount, canReadAutomatically else { return }

        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: Self.ignoredTypes) else { return }

        let foreground = NSWorkspace.shared.frontmostApplication
        if let bundleID = foreground?.bundleIdentifier,
           settings.excludedBundleIDs.contains(bundleID) { return }

        // The public pasteboard API doesn't expose a reliable source application.
        // Honor its optional cooperative source marker; otherwise use the foreground app.
        let markedSource = types.contains(Self.sourceType)
            ? pasteboard.string(forType: Self.sourceType) : nil
        let sourceBundleID = markedSource.flatMap { $0.isEmpty ? nil : $0 }
            ?? foreground?.bundleIdentifier
        if let sourceBundleID,
           sourceBundleID == Bundle.main.bundleIdentifier || settings.excludedBundleIDs.contains(sourceBundleID) {
            return
        }
        let sourceApp = sourceBundleID.flatMap {
            NSRunningApplication.runningApplications(withBundleIdentifier: $0).first?.localizedName
        } ?? foreground?.localizedName ?? L("Unknown app", "未知应用")

        if let imageType = [.png, .tiff].first(where: types.contains) {
            captureImage(type: imageType, changeCount: changeCount, sourceApp: sourceApp, sourceBundleID: sourceBundleID)
        } else if types.contains(.string), let text = pasteboard.string(forType: .string), !text.isEmpty {
            guard pasteboard.changeCount == changeCount else { return }
            store.addText(text, sourceApp: sourceApp, sourceBundleID: sourceBundleID)
            contentStatus = nil
        }
        refreshStatus()
    }

    private func captureImage(type: NSPasteboard.PasteboardType, changeCount: Int, sourceApp: String, sourceBundleID: String?) {
        let configuredLimit = settings.maxImageMB.isFinite ? settings.maxImageMB : 10
        let byteLimit = Int(min(max(configuredLimit, 0), 1024) * 1024 * 1024)
        guard byteLimit > 0 else { return }
        // There is no public preflight size API: validate bytes immediately after IPC,
        // before asking ImageIO to decode or allocate a raster.
        guard let data = pasteboard.data(forType: type) else { return }
        guard pasteboard.changeCount == changeCount else { return }
        guard data.count <= byteLimit else {
            contentStatus = L("Skipped an image larger than the configured limit.", "已跳过超过大小限制的图片。")
            return
        }
        guard let source = CGImageSourceCreateWithData(data as CFData, [kCGImageSourceShouldCache: false] as CFDictionary),
              let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [String: Any],
              let width = (properties[kCGImagePropertyPixelWidth as String] as? NSNumber)?.doubleValue,
              let height = (properties[kCGImagePropertyPixelHeight as String] as? NSNumber)?.doubleValue,
              width > 0, height > 0, width * height <= 40_000_000 else {
            contentStatus = L("Skipped an unsupported or excessively large image.", "已跳过不支持或像素过大的图片。")
            return
        }

        let pngData: Data
        if CGImageSourceGetType(source) as String? == UTType.png.identifier {
            pngData = data
        } else {
            guard let image = CGImageSourceCreateImageAtIndex(source, 0, [kCGImageSourceShouldCache: false] as CFDictionary) else { return }
            let output = NSMutableData()
            guard let destination = CGImageDestinationCreateWithData(output, UTType.png.identifier as CFString, 1, nil) else { return }
            CGImageDestinationAddImage(destination, image, nil)
            guard CGImageDestinationFinalize(destination) else { return }
            pngData = output as Data
        }
        guard pngData.count <= byteLimit else {
            contentStatus = L("Skipped an image whose PNG exceeds the configured limit.", "转换后的 PNG 超过大小限制，已跳过。")
            return
        }
        store.addImage(pngData, sourceApp: sourceApp, sourceBundleID: sourceBundleID)
        contentStatus = nil
    }
}

@MainActor
final class GlobalHotKey {
    private var hotKey: EventHotKeyRef?
    private var handler: EventHandlerRef?
    private var registeredKeyCode: UInt32?
    private var registeredModifiers: UInt32?
    private var registeredID: UInt32 = 0
    private var nextID: UInt32 = 1
    private var action: (() -> Void)?
    private static let signature: OSType = 0x54505354 // TPST

    init() {}

    deinit {
        if let hotKey { UnregisterEventHotKey(hotKey) }
        if let handler { RemoveEventHandler(handler) }
    }

    @discardableResult
    func register(keyCode: UInt32, modifiers: UInt32, action: @escaping () -> Void) -> Bool {
        if hotKey != nil, registeredKeyCode == keyCode, registeredModifiers == modifiers {
            self.action = action
            return true
        }
        if handler == nil {
            var eventType = EventTypeSpec(eventClass: OSType(kEventClassKeyboard), eventKind: UInt32(kEventHotKeyPressed))
            let installed = InstallEventHandler(
                GetApplicationEventTarget(),
                { _, event, userData in
                    guard let event, let userData else { return OSStatus(eventNotHandledErr) }
                    // Carbon dispatches application hot-key handlers on the main event loop.
                    return MainActor.assumeIsolated {
                        Unmanaged<GlobalHotKey>.fromOpaque(userData).takeUnretainedValue().handle(event)
                    }
                },
                1, &eventType, Unmanaged.passUnretained(self).toOpaque(), &handler
            )
            guard installed == noErr else { return false }
        }

        let candidateID = nextID
        nextID &+= 1
        var candidate: EventHotKeyRef?
        let result = RegisterEventHotKey(
            keyCode, modifiers,
            EventHotKeyID(signature: Self.signature, id: candidateID),
            GetApplicationEventTarget(), 0, &candidate
        )
        // Register first: a conflicting new shortcut never discards the working one.
        guard result == noErr, let candidate else { return false }
        if let hotKey { UnregisterEventHotKey(hotKey) }
        hotKey = candidate
        registeredKeyCode = keyCode
        registeredModifiers = modifiers
        registeredID = candidateID
        self.action = action
        return true
    }

    func unregister() {
        if let hotKey { UnregisterEventHotKey(hotKey) }
        if let handler { RemoveEventHandler(handler) }
        hotKey = nil
        handler = nil
        registeredKeyCode = nil
        registeredModifiers = nil
        action = nil
    }

    private func handle(_ event: EventRef) -> OSStatus {
        var identifier = EventHotKeyID()
        let result = GetEventParameter(event, EventParamName(kEventParamDirectObject), EventParamType(typeEventHotKeyID), nil, MemoryLayout<EventHotKeyID>.size, nil, &identifier)
        guard result == noErr,
              identifier.signature == Self.signature,
              identifier.id == registeredID else { return OSStatus(eventNotHandledErr) }
        action?()
        return noErr
    }
}

@MainActor
final class PasteService: ObservableObject {
    @Published var message: String?
    var targetApplication: NSRunningApplication?
    private let monitor: ClipboardMonitor
    private var pasteRequestID = UUID()

    init(monitor: ClipboardMonitor) {
        self.monitor = monitor
    }

    var accessibilityGranted: Bool {
        AXIsProcessTrusted() && CGPreflightPostEventAccess()
    }

    func rememberTarget(preservingCurrentTarget: Bool = false) {
        // Opening history from our own settings must never reuse an older app.
        // A new presentation also invalidates an earlier delayed paste request.
        pasteRequestID = UUID()
        if preservingCurrentTarget { return }
        guard let application = NSWorkspace.shared.frontmostApplication,
              application.processIdentifier != ProcessInfo.processInfo.processIdentifier,
              !application.isTerminated else {
            targetApplication = nil
            return
        }
        targetApplication = application
    }

    func paste(_ item: ClipboardItem, dismiss: @escaping () -> Void) {
        message = nil
        guard monitor.copy(item) else {
            message = monitor.status ?? L("Unable to copy this item.", "无法复制此条目。")
            return
        }
        let copiedChangeCount = monitor.currentChangeCount
        guard accessibilityGranted else {
            message = L("Copied. Press ⌘V to paste. Allow Accessibility access for direct paste.", "已复制，请按 ⌘V 粘贴。允许辅助功能后可直接粘贴。")
            dismiss()
            return
        }
        guard let target = targetApplication, !target.isTerminated,
              target.processIdentifier != ProcessInfo.processInfo.processIdentifier else {
            message = L("Copied. Focus an input field and press ⌘V.", "已复制。请聚焦输入框后按 ⌘V。")
            dismiss()
            return
        }

        let requestID = UUID()
        pasteRequestID = requestID
        dismiss()
        guard target.activate(options: []) else {
            message = L("Copied, but the target app could not be activated. Press ⌘V to paste.", "已复制，但无法激活目标应用。请按 ⌘V 粘贴。")
            return
        }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.18) { [weak self] in
            guard let self, self.pasteRequestID == requestID else { return }
            guard self.accessibilityGranted,
                  self.monitor.currentChangeCount == copiedChangeCount,
                  NSWorkspace.shared.frontmostApplication?.processIdentifier == target.processIdentifier,
                  !target.isTerminated else {
                self.message = L("Automatic paste stopped because focus, clipboard contents, or permission changed.", "焦点、剪贴板内容或权限发生变化，已取消自动粘贴。")
                return
            }
            guard let source = CGEventSource(stateID: .combinedSessionState),
                  let keyDown = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: true),
                  let keyUp = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: false) else {
                self.message = L("Copied. Press ⌘V to paste.", "已复制。请按 ⌘V 粘贴。")
                return
            }
            keyDown.flags = .maskCommand
            keyUp.flags = .maskCommand
            keyDown.post(tap: .cghidEventTap)
            keyUp.post(tap: .cghidEventTap)
            // Event posting doesn't report whether the focused control accepted a paste.
            self.message = nil
        }
    }

    func requestAccessibility() {
        let options = [kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String: true] as CFDictionary
        if !AXIsProcessTrustedWithOptions(options) {
            message = L("Enable PastePad in Privacy & Security → Accessibility, then try again.", "请在隐私与安全性 → 辅助功能中允许 PastePad，然后重试。")
            openAccessibilitySettings()
        } else if !CGPreflightPostEventAccess() {
            _ = CGRequestPostEventAccess()
        }
    }

    func openAccessibilitySettings() {
        if let url = URL(string: "x-apple.systempreferences:com.apple.preference.security?Privacy_Accessibility") {
            NSWorkspace.shared.open(url)
        }
    }
}
